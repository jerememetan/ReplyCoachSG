def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        for i, (scenario, intent, history, message, target) in enumerate(CASES, 1):
            row = {
                "id": f"DIAG-LC-{i:03d}",
                "split": "dev",
                "scenario": scenario,
                "intent": intent,
                "session_memory": [
                    {"speaker": speaker, "text": text}
                    for speaker, text in history
                ],
                "message": {
                    "text": f"peer: {message}",
                    "language_mix": ["en"],
                    "local_terms": [],
                },
                "replies": {"standard": "", "local": ""},
                "author": "team",
                "reviewer": "",
                "second_reviewer": "",
                "reviewer_notes": "",
                "second_reviewer_notes": "",
                "notes": (
                    "LONG-CONTEXT DIAGNOSTIC; draft case requiring team review. "
                    f"Expected relevant context: {target}"
                ),
                "privacy_ok": True,
                "licence": "team-authored",
                "origin": "engineering_fixture",
                "status": "draft_needs_team_review",
            }
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Wrote {len(CASES)} diagnostic cases to {OUT}")

if __name__ == "__main__":
    main()

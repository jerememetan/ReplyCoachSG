"""GPU inference with a learned-abstention English adapter and old Singlish."""
import argparse
import importlib.util
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT))
import run_sealion_abstention_v3_core as experiment
core=experiment.core


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inputs',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--checkpoint',type=Path)
    args=parser.parse_args()
    assert Path.home().name=='hm.teoh.2024'
    if args.output.exists():raise FileExistsError(args.output)
    core.torch.set_num_threads(4)
    checkpoint=args.checkpoint
    if checkpoint is None:
        checkpoint=ROOT/'outputs/selective_abstention/selected'
    spec=importlib.util.spec_from_file_location('export',core.BUNDLE/'infer.py')
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    module.verify_files(core.BUNDLE)
    rows=json.loads(args.inputs.read_text());module.validate_inputs(rows)
    rows=[{**{k:r[k] for k in ['item_id','context','speakers','message']},
        'requires_refusal':None,'reference_values':[],'scope':'custom_user_inference'} for r in rows]
    model=core.load(checkpoint)
    model.load_adapter(core.BUNDLE/'adapters/singlish',adapter_name='singlish',is_trainable=False)
    result=experiment.paired_evaluation(model,core.checkpoint_tokenizer(core.BUNDLE/'base'),rows,str(args.output.resolve()))
    result.pop('metrics',None)  # Custom inputs have no answerability gold labels.
    for row in result['outputs']:
        row['abstention_state']='canonical' if row['canonical_abstention'] else 'uncertainty_cue' if row['uncertainty_cue'] else 'generated_draft'
        if row['uncertainty_cue'] and not row['canonical_abstention']:row['needs_more_context']=None
    result.update(checkpoint=str(checkpoint),checkpoint_sha256=core.sha(checkpoint/'adapter_model.safetensors'),
        inputs_sha256=core.sha(args.inputs),gpu=core.torch.cuda.get_device_name(0),
        training_performed=False,context_rule_layer_used=False,script_sha256=core.sha(Path(__file__)),
        note='English is generated by the selected English adapter. Only an exact model-emitted refusal bypasses Singlish rewriting; other uncertainty is separately flagged. No input-based refusal rule or forced answer label.')
    args.output.write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
    print(json.dumps({k:v for k,v in result.items() if k!='outputs'}),flush=True)


if __name__=='__main__':main()
